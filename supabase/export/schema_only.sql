create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create function public.user_has_role(p_user_id bigint, p_role_name public.role_name)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.user_roles ur
    join public.roles r on r.role_id = ur.role_id
    where ur.user_id = p_user_id
      and r.role_name = p_role_name
  );
$$;

create function public.is_admin(p_user_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.user_has_role(p_user_id, 'ADMIN'::public.role_name);
$$;

create function public.current_app_user_id()
returns bigint
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with claims as (
    select auth.jwt() as jwt, auth.uid() as supabase_uid
  )
  select coalesce(
    case
      when (jwt ->> 'app_user_id') ~ '^[0-9]+$'
        then (jwt ->> 'app_user_id')::bigint
      else null
    end,
    (
      select u.user_id
      from public.users u
      where u.user_uuid = supabase_uid
      limit 1
    )
  )
  from claims;
$$;

create function public.current_app_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select public.is_admin(public.current_app_user_id());
$$;

create function public.grant_admin_role(p_user_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  admin_role_id smallint;
begin
  select role_id into admin_role_id from public.roles where role_name = 'ADMIN';
  if admin_role_id is null then
    raise exception 'Rolul ADMIN nu există.';
  end if;

  insert into public.user_roles(user_id, role_id)
  values (p_user_id, admin_role_id)
  on conflict do nothing;

  return true;
end;
$$;

create function public.revoke_admin_role(p_user_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  admin_role_id smallint;
begin
  select role_id into admin_role_id from public.roles where role_name = 'ADMIN';
  if admin_role_id is null then
    return false;
  end if;

  delete from public.user_roles
  where user_id = p_user_id
    and role_id = admin_role_id;

  return true;
end;
$$;

create function public.validate_user_is_customer()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if public.user_has_role(new.user_id, 'ADMIN'::public.role_name) then
    raise exception 'Administratorii nu pot folosi această resursă.';
  end if;
  return new;
end;
$$;

