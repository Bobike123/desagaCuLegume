create function public.prepare_cart_item()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  product_row public.products%rowtype;
begin
  select *
  into product_row
  from public.products
  where product_id = new.product_id
    and deleted_at is null;

