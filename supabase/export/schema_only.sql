  no maxvalue
  cache 1;

create table public.sessions (
  session_id uuid primary key default gen_random_uuid(),
  user_id bigint not null references public.users(user_id) on update cascade on delete restrict,
  session_token_hash text not null unique,
  status public.session_status not null default 'ACTIVE',
  created_at timestamptz not null default now(),
  last_activity_at timestamptz not null default now(),
  expires_at timestamptz not null,
  ended_at timestamptz,
  ip_address inet,
  user_agent text,
  constraint sessions_expiry_check check (expires_at > created_at),
  constraint sessions_ended_at_check check (ended_at is null or ended_at >= created_at),
  constraint sessions_status_end_check check (
    (status = 'ACTIVE' and ended_at is null)
    or (status <> 'ACTIVE' and ended_at is not null)
  )
);

