create table public.users (
  user_id bigint generated by default as identity primary key,
  user_uuid uuid not null default gen_random_uuid() unique,
  username varchar(80) not null unique,
  email varchar(255) not null unique,
  password_hash text not null,
  status public.user_status not null default 'ACTIVE',
  full_name text,
  phone varchar(50),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint users_deleted_state_check check (
    (status = 'DELETED' and deleted_at is not null)
    or (status <> 'DELETED' and deleted_at is null)
  ),
  constraint users_password_hash_format_check check (
    password_hash like 'scrypt:v1:%'
    or password_hash ~ '^[a-f0-9]{32}:[a-f0-9]{128}$'
  )
);

create table public.roles (
  role_id smallint generated by default as identity primary key,
  role_name public.role_name not null unique,
  description text
);

create table public.user_roles (
  user_id bigint not null references public.users(user_id) on update cascade on delete cascade,
  role_id smallint not null references public.roles(role_id) on update cascade on delete restrict,
  assigned_at timestamptz not null default now(),
  primary key (user_id, role_id)
);

